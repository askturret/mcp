/**
 * Synthetic OpenAPI specs of a chosen size (#197).
 *
 * `docs/reference-architecture.md` §2 claims memory is "dominated by the
 * compiled registry, which is a function of spec size, not of traffic". That is
 * a claim about a slope, and one spec cannot measure a slope — so the harness
 * needs specs at several sizes with everything else held constant.
 *
 * Real-world specs are the wrong instrument for that: they vary in operation
 * count AND in schema complexity at the same time, so a line fitted through
 * them would confound the two. These are deliberately uniform — every operation
 * carries the same shape — so operation count is the only thing that changes
 * and the slope means what it says.
 *
 * The trade-off is stated rather than hidden: the resulting bytes-per-operation
 * describes an operation of THIS complexity. `run.mjs` also measures the real
 * Petstore fixture, so the report can show where a hand-written spec falls
 * relative to the synthetic line instead of assuming they agree.
 */

/**
 * An operation with a parameter, a request-shaped response schema and prose.
 *
 * Sized to sit in the same range as the Petstore fixture's operations. A
 * minimal `{responses: {200: {description}}}` operation would compile to almost
 * nothing and would understate bytes-per-operation for any real adopter.
 */
function operation(index) {
  return {
    operationId: `getResource${index}`,
    summary: `Fetch resource ${index}`,
    description:
      `Returns resource ${index}. Synthetic operation generated by the sizing ` +
      `harness so that operation count can be varied while schema shape is held constant.`,
    parameters: [
      {
        name: 'resourceId',
        in: 'path',
        required: true,
        description: 'Identifier of the resource to fetch.',
        schema: { type: 'string' },
      },
      {
        name: 'limit',
        in: 'query',
        required: false,
        description: 'Maximum number of records to return.',
        schema: { type: 'integer', minimum: 1, maximum: 100, default: 20 },
      },
    ],
    responses: {
      200: {
        description: 'The requested resource.',
        content: {
          'application/json': {
            schema: {
              type: 'object',
              properties: {
                id: { type: 'integer' },
                name: { type: 'string' },
                tag: { type: 'string' },
                createdAt: { type: 'string', format: 'date-time' },
              },
              required: ['id', 'name'],
            },
          },
        },
      },
      404: { description: 'No such resource.' },
    },
  };
}

/**
 * Build a spec with exactly `operationCount` operations.
 *
 * @param upstreamUrl The `servers` entry. Passed in rather than defaulted so
 * this never repoints a shared fixture at localhost — `examples/petstore-light`
 * is shared with `packages/reliability` and rewriting its `servers` would break
 * that suite.
 */
export function syntheticSpec(operationCount, upstreamUrl) {
  const paths = {};
  for (let i = 0; i < operationCount; i++) {
    paths[`/resource${i}/{resourceId}`] = { get: operation(i) };
  }

  return {
    openapi: '3.0.3',
    info: {
      title: `Synthetic sizing spec (${operationCount} operations)`,
      version: '1.0.0',
      description: 'Generated by packages/gateway/bench for issue #197. Not a real API.',
    },
    servers: [{ url: upstreamUrl }],
    paths,
  };
}

/** The tool name the gateway will expose for operation `index`. */
export function syntheticToolName(index) {
  return `getResource${index}`;
}
